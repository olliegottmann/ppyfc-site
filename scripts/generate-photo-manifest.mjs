// Regenerates src/data/photos.ts from whatever is in public/photos.
// Drop new images in that folder and run `npm run photos`.
import { readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = join(process.cwd(), 'public', 'photos')
const files = readdirSync(dir)
  .filter((f) => /\.(jpe?g|png|webp)$/i.test(f))
  .sort()

const body = files.map((f) => `  '/photos/${encodeURI(f)}',`).join('\n')

writeFileSync(
  join(process.cwd(), 'src', 'data', 'photos.ts'),
  `// Generated by scripts/generate-photo-manifest.mjs - do not edit by hand.\n` +
    `// Run \`npm run photos\` after adding or removing images in public/photos.\n\n` +
    `export const photos: string[] = [\n${body}\n]\n`,
)

console.log(`wrote ${files.length} photos to src/data/photos.ts`)
